"""Data validation and data-quality report (JSON + Markdown)."""
from __future__ import annotations

import json
from typing import Any, Dict

import pandas as pd

from . import config
from .data_ingestion import build_cohort, file_sha256
from healthrisk_runtime.features import (
    AGE_BRACKETS, DIABETES_MEDICATIONS, EXCLUDED_COLUMNS, NUMERIC_INPUTS, TARGET_RAW,
)

VALID_VALUES = {
    "gender": {"Female", "Male"},
    "age": set(AGE_BRACKETS),
    "readmitted": {"<30", ">30", "NO"},
    "max_glu_serum": {"None", "Norm", ">200", ">300"},
    "A1Cresult": {"None", "Norm", ">7", ">8"},
    "change": {"No", "Ch"},
    "diabetesMed": {"No", "Yes"},
    **{m: {"No", "Steady", "Up", "Down"} for m in DIABETES_MEDICATIONS},
}
ID_RANGES = {"admission_type_id": (1, 8), "discharge_disposition_id": (1, 30), "admission_source_id": (1, 26)}


def quality_checks(df: pd.DataFrame) -> Dict[str, Any]:
    n = len(df)
    missing = (df.isna().mean() * 100).round(2)
    invalid: Dict[str, int] = {}
    for col, allowed in VALID_VALUES.items():
        bad = int((~df[col].isin(allowed) & df[col].notna()).sum())
        if bad:
            invalid[col] = bad
    for col, (lo, hi) in ID_RANGES.items():
        bad = int((~df[col].between(lo, hi)).sum())
        if bad:
            invalid[col] = bad
    for col, spec in NUMERIC_INPUTS.items():
        bad = int((df[col] < 0).sum())
        if bad:
            invalid[f"{col} (negative)"] = bad
    enc_per_patient = df.groupby("patient_nbr").size()
    constant = [c for c in df.columns if df[c].nunique(dropna=False) <= 1]
    return {
        "rows": int(n),
        "columns": int(df.shape[1]),
        "unique_encounters": int(df["encounter_id"].nunique()),
        "unique_patients": int(df["patient_nbr"].nunique()),
        "duplicate_encounter_ids": int(df["encounter_id"].duplicated().sum()),
        "duplicate_rows": int(df.duplicated().sum()),
        "patients_with_multiple_encounters": int((enc_per_patient > 1).sum()),
        "max_encounters_per_patient": int(enc_per_patient.max()),
        "encounters_from_repeat_patients_pct": round(float((df["patient_nbr"].map(enc_per_patient) > 1).mean() * 100), 2),
        "missing_pct": {k: float(v) for k, v in missing[missing > 0].sort_values(ascending=False).items()},
        "invalid_values": invalid,
        "constant_columns": constant,
        "target_distribution": {k: int(v) for k, v in df[TARGET_RAW].value_counts().items()},
    }


def write_quality_report(df: pd.DataFrame) -> Dict[str, Any]:
    checks = quality_checks(df)
    cohort, log = build_cohort(df)
    report = {
        "dataset_file": config.RAW_CSV.name,
        "dataset_sha256": file_sha256(config.RAW_CSV) if config.RAW_CSV.exists() else None,
        "checks": checks,
        "cohort": log,
        "cohort_positive_rate": round(float(cohort["readmitted_30d"].mean()), 4),
        "excluded_columns": EXCLUDED_COLUMNS,
    }
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "data_quality_report.json").write_text(json.dumps(report, indent=2))
    (config.REPORTS_DIR / "data_quality_report.md").write_text(_markdown(report))
    return report


def _markdown(r: Dict[str, Any]) -> str:
    c = r["checks"]
    lines = [
        "# Data-quality report", "",
        f"*Generated by `python -m ml.data_ingestion` from `{r['dataset_file']}` "
        f"(sha256 `{(r['dataset_sha256'] or '')[:16]}…`). All numbers are computed, not hand-written.*", "",
        "## Dimensions", "",
        f"- Rows: **{c['rows']:,}**, columns: **{c['columns']}**",
        f"- Unique encounters: {c['unique_encounters']:,}; unique patients: {c['unique_patients']:,}",
        f"- Patients with >1 encounter: {c['patients_with_multiple_encounters']:,} "
        f"(max {c['max_encounters_per_patient']} encounters for one patient); "
        f"{c['encounters_from_repeat_patients_pct']}% of encounters belong to repeat patients "
        "→ patient-group-aware splitting is required.",
        f"- Duplicate encounter ids: {c['duplicate_encounter_ids']}; fully duplicated rows: {c['duplicate_rows']}", "",
        "## Missing values (% of rows, '?' treated as missing)", "",
        "| Column | Missing % |", "|---|---|",
        *[f"| {k} | {v} |" for k, v in c["missing_pct"].items()], "",
        "## Invalid / out-of-domain values", "",
        *([f"- `{k}`: {v:,} rows" for k, v in c["invalid_values"].items()] or ["- None found"]), "",
        f"## Constant columns\n\n- {', '.join(c['constant_columns']) or 'None'}", "",
        "## Target distribution (raw `readmitted`)", "",
        *[f"- `{k}`: {v:,} ({v / c['rows'] * 100:.1f}%)" for k, v in c["target_distribution"].items()], "",
        "## Modelling cohort", "",
        *[f"- {k.replace('_', ' ')}: {v:,}" for k, v in r["cohort"].items()],
        f"- 30-day readmission rate in cohort: **{r['cohort_positive_rate'] * 100:.2f}%**", "",
        "## Columns excluded from model inputs", "",
        "| Column | Reason |", "|---|---|",
        *[f"| {k} | {v} |" for k, v in r["excluded_columns"].items()], "",
    ]
    return "\n".join(lines)
